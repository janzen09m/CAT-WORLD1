export const GET_CAT_BY_ID = (id: string): CatSkin => {
  return CAT_SKINS.find(c => c.id === id) || CAT_SKINS[0];
};

export const getDuplicateCoinBonus = (cat: CatSkin): number => {
  if (cat.duplicateCoinBonus) return cat.duplicateCoinBonus;
  if (cat.resaleValue) return cat.resaleValue;
  switch (cat.rarity) {
    case 'common': return 60;
    case 'uncommon': return 150;
    case 'rare': return 400;
    case 'epic': return 1200;
    case 'legendary': return 4000;
    case 'mythic': return 15000;
    default: return 100;
  }
};
